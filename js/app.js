        function deleteNode(nodeId) {
            if (nodeId === mindmap.center) {
                alert('Cannot delete center node');
                return;
            }
            const node = mindmap.nodes[nodeId];
            if (!node) return;

            if (node.parent) {
                const parent = mindmap.nodes[node.parent];
                if (parent) parent.children = parent.children.filter(id => id !== nodeId);
            }

            function deleteAllChildren(id) {
                const n = mindmap.nodes[id];
                if (n && n.children) {
                    n.children.forEach(childId => deleteAllChildren(childId));
                }
                delete mindmap.nodes[id];
            }
            deleteAllChildren(nodeId);

            if (mindmap.links) {
                mindmap.links = mindmap.links.filter(l => mindmap.nodes[l.from] && mindmap.nodes[l.to]);
            }

            if (mindmap.groups) {
                mindmap.groups = mindmap.groups.filter(g => g.id !== nodeId);
                mindmap.groups.forEach(g => {
                    g.nodes = g.nodes.filter(id => id !== nodeId);
                });
            }

            selection.selectedIds = selection.selectedIds.filter(id => id !== nodeId);
            if (selection.nodeId === nodeId) selection.nodeId = null;
            saveHistory();
            closeRightPanel();
            render();
        }

        function copySelected() {
            if (selection.selectedIds.length === 0) {
                if (selection.nodeId) selection.selectedIds = [selection.nodeId];
                else return;
            }

            const ids = selection.selectedIds;
            const nodesData = {};
            const linksData = [];

            ids.forEach(id => {
                const node = mindmap.nodes[id];
                if (node) {
                    nodesData[id] = JSON.parse(JSON.stringify(node));
                }
            });

            ids.forEach(id => {
                const node = mindmap.nodes[id];
                if (node && node.children) {
                    node.children.forEach(childId => {
                        if (ids.includes(childId)) {
                            linksData.push({
                                type: 'tree',
                                parentId: id,
                                childId: childId
                            });
                        }
                    });
                }
            });

            if (mindmap.links) {
                mindmap.links.forEach(link => {
                    if (ids.includes(link.from) && ids.includes(link.to)) {
                        linksData.push({
                            type: 'custom',
                            link: JSON.parse(JSON.stringify(link))
                        });
                    }
                });
            }

            clipboard = {
                nodes: nodesData,
                links: linksData,
                ids: ids
            };
        }

        function pasteSelected() {
            if (!clipboard || !clipboard.nodes || Object.keys(clipboard.nodes).length === 0) return;

            const newIds = {};
            const offset = 40;
            const idMap = {};

            Object.keys(clipboard.nodes).forEach(oldId => {
                const copiedNode = clipboard.nodes[oldId];
                const newNode = JSON.parse(JSON.stringify(copiedNode));
                newNode.id = mindmap.nextId++;
                newNode.x = copiedNode.x + offset;
                newNode.y = copiedNode.y + offset;
                newNode.children = [];
                newNode.parent = null;
                newNode.collapsed = false;
                newNode.isFree = true;
                newNode.side = null;
                if (newNode.isGroup) newNode.groupChildren = [];

                mindmap.nodes[newNode.id] = newNode;
                newIds[oldId] = newNode.id;
                idMap[oldId] = newNode.id;
            });

            if (clipboard.links) {
                clipboard.links.forEach(linkData => {
                    if (linkData.type === 'tree') {
                        const newParentId = idMap[linkData.parentId];
                        const newChildId = idMap[linkData.childId];
                        if (newParentId && newChildId) {
                            const parent = mindmap.nodes[newParentId];
                            const child = mindmap.nodes[newChildId];
                            if (parent && child) {
                                parent.children.push(newChildId);
                                child.parent = newParentId;
                            }
                        }
                    } else if (linkData.type === 'custom') {
                        const link = linkData.link;
                        const newFromId = idMap[link.from];
                        const newToId = idMap[link.to];
                        if (newFromId && newToId) {
                            const newLink = JSON.parse(JSON.stringify(link));
                            newLink.id = mindmap.nextId++;
                            newLink.from = newFromId;
                            newLink.to = newToId;
                            mindmap.links.push(newLink);
                        }
                    }
                });
            }

            const newIdList = Object.values(newIds);
            selection.selectedIds = newIdList;
            selection.nodeId = newIdList[0] || null;
            saveHistory();
            render();
            if (selection.nodeId) showRightPanel(selection.nodeId);
        }

