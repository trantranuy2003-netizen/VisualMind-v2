        function escapeHtml(str) {
            return String(str || '').replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g,
                '&gt;');
        }

        function toHex(c) {
            if (!c) return '#e0e0e0';
            if (/^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(c)) {
                if (c.length === 4) return '#' + c[1] + c[1] + c[2] + c[2] + c[3] + c[3];
                return c;
            }
            return '#e0e0e0';
        }

