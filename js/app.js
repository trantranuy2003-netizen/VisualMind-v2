        function updateNodeProperty(nodeId, prop, value) {
            const node = mindmap.nodes[nodeId];
            if (!node) return;
            const COLOR_PROPS = ['color', 'textColor', 'highlightColor'];
            const isBatch = COLOR_PROPS.includes(prop) && selection.selectedIds.length > 1 && selection.selectedIds
                .includes(nodeId);
            const targetIds = isBatch ? selection.selectedIds : [nodeId];
            targetIds.forEach(id => {
                const n = mindmap.nodes[id];
                if (!n) return;
                n[prop] = value;
                if (prop === 'textColor') n.textColorManual = true;
                if ((prop === 'text' || prop === 'icon' || prop === 'fontSize' || prop === 'bold' || prop === 'italic' ||
                        prop === 'underline') && !n.isTable) {
                    n.height = measureNodeHeight(n);
                }
            });
            saveHistory();
            showRightPanel(nodeId);
            render();
        }

