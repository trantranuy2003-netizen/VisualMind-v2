        function onSnippingMove(e) {
            if (!snippingStart) {
                snippingBox.style.display = 'none';
                return;
            }
            const rect = snippingOverlay.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const y = e.clientY - rect.top;
            snippingEnd = { x, y };
            const left = Math.min(snippingStart.x, snippingEnd.x);
            const top = Math.min(snippingStart.y, snippingEnd.y);
            const width = Math.abs(snippingEnd.x - snippingStart.x);
            const height = Math.abs(snippingEnd.y - snippingStart.y);
            snippingBox.style.display = 'block';
            snippingBox.style.left = left + 'px';
            snippingBox.style.top = top + 'px';
            snippingBox.style.width = width + 'px';
            snippingBox.style.height = height + 'px';
        }

        function onSnippingDown(e) {
            const rect = snippingOverlay.getBoundingClientRect();
            snippingStart = { x: e.clientX - rect.left, y: e.clientY - rect.top };
            snippingEnd = null;
        }

        function onSnippingUp(e) {
            if (!snippingStart || !snippingEnd) {
                cancelSnipping();
                return;
            }
            const rect = snippingOverlay.getBoundingClientRect();
            const scaleX = canvas.width / rect.width;
            const scaleY = canvas.height / rect.height;
            const x1 = Math.min(snippingStart.x, snippingEnd.x) * scaleX;
            const y1 = Math.min(snippingStart.y, snippingEnd.y) * scaleY;
            const x2 = Math.max(snippingStart.x, snippingEnd.x) * scaleX;
            const y2 = Math.max(snippingStart.y, snippingEnd.y) * scaleY;
            const w = Math.max(10, x2 - x1);
            const h = Math.max(10, y2 - y1);

            cancelSnipping();
            captureArea(x1, y1, w, h);
        }

        function onSnippingKey(e) {
            if (e.key === 'Escape') { cancelSnipping(); }
        }

        function cancelSnipping() {
            if (snippingOverlay) {
                snippingOverlay.removeEventListener('mousemove', onSnippingMove);
                snippingOverlay.removeEventListener('mousedown', onSnippingDown);
                snippingOverlay.removeEventListener('mouseup', onSnippingUp);
                snippingOverlay.remove();
                snippingOverlay = null;
            }
            if (snippingInfo) {
                snippingInfo.remove();
                snippingInfo = null;
            }
            snippingBox = null;
            snippingStart = null;
            snippingEnd = null;
            document.removeEventListener('keydown', onSnippingKey);
        }

