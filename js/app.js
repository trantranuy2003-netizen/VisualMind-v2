        function groupSelected() {
            const ids = selection.selectedIds;
            if (ids.length < 2) {
                alert('Please select at least 2 nodes to group');
                return;
            }
            const existingGroups = mindmap.groups || [];
            for (const group of existingGroups) {
                for (const id of ids) {
                    if (group.nodes.includes(id)) {
                        alert('Some nodes are already in a group.');
                        return;
                    }
                }
            }
            const groupNode = {
                id: mindmap.nextId++,
                text: 'Group',
                children: [],
                parent: null,
                x: 0,
                y: 0,
                width: 200,
                height: 80,
                fontSize: 13,
                color: '#3B82F6',
                textColor: '#fff',
                icon: '📦',
                collapsed: false,
                side: null,
                isGroup: true,
                groupChildren: [...ids],
                isTable: false,
                tableData: []
            };
            let minX = Infinity,
                minY = Infinity,
                maxX = -Infinity,
                maxY = -Infinity;
            ids.forEach(id => {
                const n = mindmap.nodes[id];
                if (n) {
                    minX = Math.min(minX, n.x);
                    minY = Math.min(minY, n.y);
                    maxX = Math.max(maxX, n.x + n.width);
                    maxY = Math.max(maxY, n.y + n.height);
                }
            });
            if (isFinite(minX)) {
                groupNode.x = (minX + maxX) / 2 - groupNode.width / 2;
                groupNode.y = (minY + maxY) / 2 - groupNode.height / 2;
            }
            groupNode.height = measureNodeHeight(groupNode);
            mindmap.nodes[groupNode.id] = groupNode;
            if (!mindmap.groups) mindmap.groups = [];
            mindmap.groups.push({ id: groupNode.id, nodes: [...ids] });
            const center = mindmap.center;
            const centerNode = mindmap.nodes[center];
            if (centerNode) {
                ids.forEach(id => {
                    const idx = centerNode.children.indexOf(id);
                    if (idx > -1) centerNode.children.splice(idx, 1);
                });
                centerNode.children.push(groupNode.id);
                groupNode.parent = center;
                groupNode.side = centerNode.children.length % 2 === 0 ? 'right' : 'left';
            }
            saveHistory();
            selection.selectedIds = [groupNode.id];
            selection.nodeId = groupNode.id;
            render();
            showRightPanel(groupNode.id);
        }

        function ungroupSelected() {
            const ids = selection.selectedIds;
            if (ids.length === 0) return;
            let groupId = null;
            for (const id of ids) {
                const node = mindmap.nodes[id];
                if (node && node.isGroup) { groupId = id; break; }
            }
            if (!groupId) {
                alert('Please select a group node to ungroup');
                return;
            }
            const groupNode = mindmap.nodes[groupId];
            const groupData = mindmap.groups.find(g => g.id === groupId);
            if (!groupData) return;
            const center = mindmap.center;
            const centerNode = mindmap.nodes[center];
            if (centerNode) {
                const idx = centerNode.children.indexOf(groupId);
                if (idx > -1) centerNode.children.splice(idx, 1);
                groupData.nodes.forEach(id => {
                    const node = mindmap.nodes[id];
                    if (node) {
                        node.parent = center;
                        node.isGroup = false;
                        centerNode.children.push(id);
                    }
                });
            }
            delete mindmap.nodes[groupId];
            mindmap.groups = mindmap.groups.filter(g => g.id !== groupId);
            saveHistory();
            selection.selectedIds = groupData.nodes;
            selection.nodeId = groupData.nodes.length > 0 ? groupData.nodes[0] : null;
            render();
            closeRightPanel();
        }

        function createLinkBetweenNodes(fromId, toId) {
            if (fromId === toId) return;
            if (!mindmap.links) mindmap.links = [];
            const exists = mindmap.links.some(l => (l.from === fromId && l.to === toId) || (l.from === toId && l.to ===
                fromId));
            if (exists) return;
            const link = {
                id: mindmap.nextId++,
                from: fromId,
                to: toId,
                color: '#3B82F6',
                dashed: false,
                dashLength: 8,
                gapLength: 6,
                opacity: 0.7,
                width: 2.5
            };
            mindmap.links.push(link);
            saveHistory();
            render();
            selection.selectedLink = { linkId: link.id };
            showLinkPanel(link);
        }

        function showSaveModal() {
            const overlay = document.createElement('div');
            overlay.className = 'modal-overlay';
            overlay.id = 'saveModal';
            const defaultName = 'mindmap';
            overlay.innerHTML = `
                    <div class="modal-box">
                        <h3>${t('save-modal-title')}</h3>
                        <p>${t('save-modal-desc')}</p>
                        <input type="text" id="saveFileName" value="${defaultName}" placeholder="${t('save-modal-placeholder')}" autofocus>
                        <div class="modal-actions">
                            <button class="btn-cancel" onclick="closeSaveModal()">${t('save-modal-cancel')}</button>
                            <button class="btn-confirm" onclick="confirmSave()">${t('save-modal-confirm')}</button>
                        </div>
                    </div>
                `;
            document.body.appendChild(overlay);
            const input = document.getElementById('saveFileName');
            setTimeout(() => { input.focus();
                input.select(); }, 50);
            input.addEventListener('keydown', (e) => {
                if (e.key === 'Enter') confirmSave();
                else if (e.key === 'Escape') closeSaveModal();
            });
            overlay.addEventListener('click', (e) => { if (e.target === overlay) closeSaveModal(); });
        }

        function closeSaveModal() {
            const modal = document.getElementById('saveModal');
            if (modal) modal.remove();
        }

        async function confirmSave() {
            const input = document.getElementById('saveFileName');
            let filename = input.value.trim();
            if (!filename) filename = 'mindmap';
            if (!filename.endsWith('.json')) filename += '.json';
            // Make sure flashcards are included
            const json = JSON.stringify(mindmap, null, 2);
            if (!await requireAuthForSave({ type: 'mindmap', filename, json })) return;
            const title = filename.replace(/\.json$/i, '');
            sessionStorage.setItem('visualmind-cloud-title', title);
            saveMindmapJson(filename, json);
            const saved = await saveMindmapToCloud(title, mindmap);
            showToast(saved ? 'Đã lưu thành công' : 'Không thể lưu lên cloud. File JSON vẫn đã được tải về.', saved ? 'success' : 'error');
        }

        function saveMindmapJson(filename, json) {
            const blob = new Blob([json], { type: 'application/json' });
            const url = URL.createObjectURL(blob);
            const a = document.createElement('a');
            a.href = url;
            a.download = filename;
            a.click();
            URL.revokeObjectURL(url);
            closeSaveModal();
        }

        function loadFromFile() {
            const input = document.getElementById('fileInput');
            input.click();
            input.onchange = (e) => {
                const file = e.target.files[0];
                if (file) {
                    const reader = new FileReader();
                    reader.onload = (event) => {
                        try {
                            const data = JSON.parse(event.target.result);
                            // Preserve flashcards if they exist in the loaded file
                            if (data.flashcards) {
                                mindmap.flashcards = data.flashcards;
                                mindmap.nextFlashcardId = (mindmap.flashcards.reduce((m, c) => Math.max(m, c.id || 0),
                                    0) + 1);
                            }
                            // Update mindmap data
                            mindmap.center = data.center;
                            mindmap.nodes = data.nodes || {};
                            mindmap.nextId = data.nextId || 1;
                            mindmap.links = data.links || [];
                            mindmap.groups = data.groups || [];

                            history = [];
                            historyIndex = -1;
                            viewport = { x: 0, y: 0, zoom: 1 };
                            updateZoomDisplay();
                            fcOrder = mindmap.flashcards.map(c => c.id);
                            fcIndex = 0;
                            fcRevealed = false;
                            render();
                            if (appMode === 'flashcard') {
                                renderFlashcardStudy();
                                renderFlashcardList();
                            }
                            showToast('✅ Import thành công!', 'success');
                        } catch (err) {
                            alert('Invalid JSON file');
                        }
                    };
                    reader.readAsText(file);
                }
            };
        }

        function showToast(msg, type) {
            // Simple toast fallback
            const el = document.getElementById('fcParsePreview') || document.createElement('div');
            if (el.id === 'fcParsePreview') {
                el.textContent = msg;
                el.style.color = type === 'success' ? '#16A34A' : '#EF4444';
                setTimeout(() => { if (el.id === 'fcParsePreview') el.textContent = ''; }, 3000);
            } else {
                el.textContent = msg;
                el.style.cssText = `position:fixed;right:24px;bottom:24px;z-index:3000;padding:12px 16px;border-radius:10px;color:#fff;background:${type === 'success' ? '#16A34A' : '#EF4444'};box-shadow:0 8px 24px rgba(0,0,0,.2);`;
                document.body.appendChild(el);
                setTimeout(() => el.remove(), 3000);
            }
        }

