        function resizeTable(nodeId, rows, cols) {
            const node = mindmap.nodes[nodeId];
            if (!node || !node.isTable) return;
            const curRows = node.tableData.length || 1;
            const curCols = node.tableData[0] ? node.tableData[0].length : 1;
            const newRows = rows !== null ? rows : curRows;
            const newCols = cols !== null ? cols : curCols;

            const newData = [];
            for (let r = 0; r < newRows; r++) {
                const row = [];
                for (let c = 0; c < newCols; c++) {
                    if (r < curRows && c < curCols) {
                        row.push(node.tableData[r][c] || '');
                    } else {
                        row.push('');
                    }
                }
                newData.push(row);
            }
            node.tableData = newData;
            node.height = measureNodeHeight(node);
            saveHistory();
            showRightPanel(nodeId);
            render();
        }

        function getTableCellAt(node, worldX, worldY) {
            const headerH = 32;
            const rows = node.tableData.length;
            const cols = node.tableData[0] ? node.tableData[0].length : 0;
            if (rows === 0 || cols === 0) return null;
            const gridY = node.y + headerH;
            const gridH = node.height - headerH;
            const rowH = gridH / rows;
            const colW = node.width / cols;
            const relX = worldX - node.x;
            const relY = worldY - gridY;
            if (relX < 0 || relX > node.width || relY < 0 || relY > gridH) return null;
            const col = Math.floor(relX / colW);
            const row = Math.floor(relY / rowH);
            if (row >= rows || col >= cols) return null;
            return { row, col };
        }

